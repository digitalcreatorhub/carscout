import { chromium } from 'playwright';
import fs from 'node:fs';
const W='https://carscout.pmax70095.workers.dev', O={origin:'https://digitalcreatorhub.github.io'};
const list=await (await fetch(W+'/api/search?url='+encodeURIComponent('https://www.ss.com/ru/transport/cars/volkswagen/'),{headers:O})).json();
const ad=(list.items||[]).find(i=>/\/msg\//.test(i.url)&&i.km);
const url=ad.url.replace('/msg/ru/','/msg/lv/').replace('www.ss.com','www.ss.lv');
const rec={url,resp:{},img:{}};
const b=await chromium.launch(); const pg=await b.newPage({viewport:{width:1400,height:900}});
pg.on('response',async r=>{ const u=r.url(); if(!u.startsWith(W)) return; try{ if(u.includes('/api/img')){ if(Object.keys(rec.img).length<80) rec.img[u]=(await r.body()).toString('base64'); } else rec.resp[u]=await r.text(); }catch(e){} });
await pg.goto('https://digitalcreatorhub.github.io/carscout/?r='+Date.now()); await pg.waitForTimeout(2500);
await pg.fill('#f-url',url); await pg.click('#btn-go');
await pg.waitForSelector('#a-verdict',{timeout:90000}).catch(()=>{});
await pg.waitForFunction(()=>{const v=window.__carscout&&window.__carscout.S.view; return v&&v.photoState==='ok';},null,{timeout:90000}).catch(()=>{});
await pg.waitForTimeout(3000);
rec.ver=await pg.evaluate(()=>document.documentElement.innerHTML.match(/APP_VER='([^']+)'/)?.[1]||'');
rec.text=await pg.evaluate(()=>document.body.innerText.slice(0,20000));
await pg.screenshot({path:'out/live.png',fullPage:true});
fs.writeFileSync('out/rec.json',JSON.stringify(rec));
console.log(url, Object.keys(rec.resp).length, Object.keys(rec.img).length);
await b.close();
